#!/usr/bin/env python3
"""Builds play.html, the embeddable page used for the Claude artifact playtest build,
plus build/assets/*.glb.json (each model as base64 JSON, because the artifact host only
serves web file types).

The artifact host wraps the page in its own <html>/<head>/<body>, so play.html is a
fragment: index.html's head assets + body markup, minus PeerJS (WebRTC is unavailable
there), plus a flag telling game.js to hide online play.

    python3 tools/build-play.py
"""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "index.html").read_text()
head = re.search(r"<head>(.*?)</head>", src, re.S).group(1)
body = re.search(r"<body>(.*?)</body>", src, re.S).group(1)
title = re.search(r"<title>.*?</title>", head, re.S).group(0)
importmap = re.search(r'<script type="importmap">.*?</script>', head, re.S).group(0)

out = f"""<!-- Generated by tools/build-play.py from index.html. Do not edit by hand. -->
{title}
<link rel="stylesheet" href="style.css" />
<style>html, body {{ height: 100%; background: #050706; }}</style>
<script>window.BLINDSIGHT_EMBED = true;</script>
{importmap}
{body.strip()}
"""
# Entity-encode non-ASCII so the fragment renders correctly whatever charset it is served with.
(root / "play.html").write_text(out.encode("ascii", "xmlcharrefreplace").decode())
print("wrote play.html")

import base64, json
out_dir = root / "build" / "assets"
out_dir.mkdir(parents=True, exist_ok=True)
for name in ("survivor.glb", "monster.glb"):
    data = base64.b64encode((root / "assets" / name).read_bytes()).decode()
    (out_dir / (name + ".json")).write_text(json.dumps({"glb": data}))
    print("wrote build/assets/" + name + ".json")
